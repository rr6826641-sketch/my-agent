def _err(msg):
    return json.dumps({"error": msg}, ensure_ascii=False)


def tool_mcp_list():
    """List all available MCP servers in the mcp_servers directory."""
    try:
        os.makedirs(MCP_DIR, exist_ok=True)
        servers = []
        for fn in sorted(os.listdir(MCP_DIR)):
            if fn.endswith(".py") and not fn.startswith("_"):
                path = os.path.join(MCP_DIR, fn)
                st = os.stat(path)
                servers.append({"file": fn, "size": st.st_size,
                                "mtime": time.strftime("%Y-%m-%d %H:%M", time.localtime(st.st_mtime))})
        return json.dumps({"ok": True, "mcp_dir": MCP_DIR,
                           "count": len(servers), "servers": servers},
                          ensure_ascii=False, indent=2)
    except Exception as exc:
        return _err("mcp_list failed: %r" % exc)


def tool_mcp_server_build(name="scanner", tools="port_scan,subdomains",
                          output_path=""):
    """Generate a new standalone MCP server file (JSON-RPC line protocol)
    with the given tool list. Stubs are returned as functional
    placeholders the operator can extend."""
    try:
        if not name:
            return _err("server name required")
        tlist = [t.strip() for t in (tools or "port_scan,subdomains").split(",") if t.strip()]

        # build a small stub function table
        stub_funcs = {}
        for t in tlist:
            stub_funcs[t] = (lambda tname=t: (lambda **kw: {
                "note": "stub - implement %s in mcp_servers/%s.py" % (tname, name),
                "args": kw}))()

        fname = "mcp_%s.py" % name
        path = output_path or os.path.join(MCP_DIR, fname)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        code = SERVER_TEMPLATE.format(name=name, fname=fname, tools=stub_funcs)
        with open(path, "w", encoding="utf-8") as f:
            f.write(code)
        return json.dumps({
            "ok": True, "server": name, "path": path,
            "tools": tlist,
            "run": "python %s" % path,
            "next": "edit %s to implement each tool body (see ai_agent/tools for ready impls)"
                    % path,
        }, ensure_ascii=False, indent=2)
    except Exception as exc:
        return _err("mcp_build failed: %r" % exc)


