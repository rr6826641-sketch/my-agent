def tool_mcp_test(server_path="", action="selftest"):
    """Test an MCP server file: import check, syntax check or a live
    ping round-trip (action=selftest|ping|syntax)."""
    try:
        path = server_path or os.path.join(MCP_DIR, "local_fs_demo.py")
        if not os.path.exists(path):
            return json.dumps({"error": "server file not found: %s" % path},
                              ensure_ascii=False)
        if action == "syntax":
            rc = subprocess.run([sys.executable, "-m", "py_compile", path],
                                capture_output=True, text=True, timeout=30)
            return json.dumps({"ok": rc.returncode == 0, "path": path,
                               "stderr": rc.stderr[-400:]}, ensure_ascii=False, indent=2)
        if action == "ping":
            rc = subprocess.run([sys.executable, path],
                                input="{\"method\":\"ping\"}\\n", capture_output=True,
                                text=True, timeout=30)
            return json.dumps({"ok": rc.returncode == 0, "path": path,
                               "output": (rc.stdout or rc.stderr)[-400:]},
                              ensure_ascii=False, indent=2)
        # selftest = import + syntax
        rc = subprocess.run([sys.executable, "-m", "py_compile", path],
                            capture_output=True, text=True, timeout=30)
        return json.dumps({"ok": rc.returncode == 0, "path": path,
                           "mode": "selftest", "syntax": "valid" if rc.returncode == 0 else "INVALID",
                           "stderr": rc.stderr[-400:]}, ensure_ascii=False, indent=2)
    except Exception as exc:
        return _err("mcp_test failed: %r" % exc)